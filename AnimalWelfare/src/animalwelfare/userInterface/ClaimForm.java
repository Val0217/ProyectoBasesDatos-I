    private void prepareForm() {
        jButton1.setEnabled(false);

        jTextArea1.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                updateSubmitButton();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                updateSubmitButton();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                updateSubmitButton();
            }
        });

        jButton1.addActionListener(this::jButton1ActionPerformed);
    }
    private void updateSubmitButton() {
        String description = jTextArea1.getText();
        jButton1.setEnabled(description != null && !description.trim().isEmpty());
    }
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            String description = jTextArea1.getText().trim();

            if (description.isEmpty()) {
                JOptionPane.showMessageDialog(
                    this,
                    "Write a description before submitting the claim."
                );
                return;
            }

            controller.createClaimRequest(petId, description);

            JOptionPane.showMessageDialog(
                this,
                "Claim request sent to the pet owner."
            );

            if (parent != null) {
                parent.refreshAfterClaimRequest();
                parent.setVisible(true);
            } else {
                new UserPetTable(currentUserId).setVisible(true);
            }

            dispose();

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                this,
                ex.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }
